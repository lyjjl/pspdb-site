// PSPDB 文档数据模型
//
// 每个文档由若干「节」组成，每节含标题与若干段落。
// 段落文本用 {{字段id}} 作为内联占位符，界面渲染为独立输入框，
// 复制全文 / 下载文件时以当前填写内容替换。

export interface Field {
  id: string
  /** 输入框的标签（对应原文中的填写提示） */
  label: string
  /** 默认/示例值 */
  defaultValue: string
  /** 原文中的【填写…】提示，用于帮助理解该填什么 */
  hint?: string
}

export function resolveParagraph(text: string, fields: Record<string, string>): string {
  return text.replace(/\{\{([^}]+)\}\}/g, (_, id: string) => fields[id] ?? "")
}

export interface Section {
  title?: string
  /** 标题层级：doc 为文档主标题（小标宋居中），h1 黑体，h2 楷体 */
  titleKind?: "doc" | "h1" | "h2"
  paragraphs: string[]
}

export interface Doc {
  id: string
  title: string
  subtitle: string
  fields: Field[]
  sections: Section[]
}

